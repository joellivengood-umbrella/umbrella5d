-- Reconcile: record production-only schema (drift) in the migrations
--
-- A read-only snapshot of production (2026-10-21, PostgreSQL 17.6) was
-- diffed against a database built purely from these migrations. Everything
-- the migrations create matched production; production additionally had the
-- objects below, created directly in the Supabase dashboard / SQL editor.
-- This migration records them so a database rebuilt from the repo (staging,
-- a restore, a new developer) matches production.
--
-- Written to be a NO-OP against production: the function is replaced with
-- an identical body, the two policies are dropped and recreated with
-- identical definitions (atomically, in this one transaction), and the
-- bucket and legacy table are only created when missing.
--
-- Not recorded on purpose — Supabase manages these itself:
--   * event trigger ensure_rls -> public.rls_auto_enable() (the dashboard's
--     "automatically enable RLS on new tables" setting)
--   * event triggers issue_graphql_placeholder, issue_pg_cron_access,
--     issue_pg_graphql_access, issue_pg_net_access, pgrst_ddl_watch,
--     pgrst_drop_watch (platform plumbing)
--
-- Idempotent: safe to re-run.

-- ── 1. is_item_published ──────────────────────────────────────────
-- RLS helper used by the content_progress write policies below. Like the
-- other RLS helpers, its EXECUTE grants stay at their defaults (policies run
-- it as the querying role; see 20261021_revoke_anon_rpc_execute.sql).
create or replace function public.is_item_published(_item_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.content_items
     where id = _item_id and is_published = true
  );
$$;

-- ── 2. content_progress write policies ────────────────────────────
-- Production only lets signed-in members complete PUBLISHED items, and has
-- the UPDATE policy that "Mark Complete" (an upsert) relies on. The repo's
-- 20260418_content_progress.sql predates both changes.
drop policy if exists "content_progress_insert_own" on public.content_progress;
create policy "content_progress_insert_own"
  on public.content_progress
  for insert
  to authenticated
  with check (auth.uid() = user_id and public.is_item_published(content_item_id));

drop policy if exists "content_progress_update_own" on public.content_progress;
create policy "content_progress_update_own"
  on public.content_progress
  for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id and public.is_item_published(content_item_id));

-- ── 3. Daily Pod audio bucket ─────────────────────────────────────
-- Public bucket holding POTD episode audio (uploaded via the dashboard;
-- episode media_url values point here).
insert into storage.buckets (id, name, public)
values ('potd', 'potd', true)
on conflict (id) do nothing;

-- ── 4. Legacy lesson_progress table ───────────────────────────────
-- Superseded by content_progress (20260418); only the retired /prototype
-- HTML pages ever used it. Recorded so rebuilt databases match production,
-- and created ONLY when missing, so this never touches the real table or
-- its rows. Candidate for removal once its data is confirmed unneeded.
do $$
begin
  if to_regclass('public.lesson_progress') is null then
    create table public.lesson_progress (
      id         bigint generated by default as identity primary key,
      user_id    uuid default gen_random_uuid(),
      lesson_id  text,
      completed  boolean,
      created_at timestamptz not null default now(),
      constraint lesson_progress_user_lesson_unique unique (user_id, lesson_id)
    );
    alter table public.lesson_progress enable row level security;
    create policy "Users can read own progress" on public.lesson_progress
      for select using (auth.uid() = user_id);
    create policy "Users can insert own progress" on public.lesson_progress
      for insert with check (auth.uid() = user_id);
    create policy "Users can update own progress" on public.lesson_progress
      for update using (auth.uid() = user_id);
    create policy "Users can delete own progress" on public.lesson_progress
      for delete using (auth.uid() = user_id);
  end if;
end $$;
